from google.colab import userdata
from openai import OpenAI

client = OpenAI(
    api_key=userdata.get("GROQ_API_KEY"),
    base_url="https://api.groq.com/openai/v1"
)

MODEL = "openai/gpt-oss-120b"

SYSTEM = """
ROLE: You are the assistant for Sweet Crumbs Home Bakery.

FACTS:
Orders need 24 hours' notice.
All cakes have eggless versions.

FORMAT:
Reply politely in under 50 words.
"""

RULES = """
RULES:
Never promise a delivery time.
If unsure, say "I'll check with the owner."
"""

def ask(system, question):
    response = client.chat.completions.create(
        model=MODEL,
        temperature=0.3,
        messages=[
            {"role": "system", "content": system},
            {"role": "user", "content": question}
        ]
    )
    return response.choices[0].message.content

question = "Can you deliver in 1 hour?"

print("Without Rules:")
print(ask(SYSTEM, question))

print("\nWith Rules:")
print(ask(SYSTEM + RULES, question))

