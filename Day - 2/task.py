SYSTEM = """
You are the assistant for Sweet Crumbs Home Bakery.
Remember customer details from the conversation.
If you do not know something, say so.
"""

history = [{"role": "system", "content": SYSTEM}]

MAX_TURNS = 2

def chat(user_text):
    history.append({"role": "user", "content": user_text})

    recent = [history[0]] + history[1:][-MAX_TURNS:]

    response = client.chat.completions.create(
        model=MODEL,
        messages=recent,
        temperature=0.3
    )

    reply = response.choices[0].message.content

    history.append({"role": "assistant", "content": reply})

    return reply

print(chat("My name is Ravi"))
print(chat("What cakes do you sell?"))
print(chat("Do you have cupcakes?"))
print(chat("Thank you"))
