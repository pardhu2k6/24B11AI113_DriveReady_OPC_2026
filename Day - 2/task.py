import json

MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}

def get_price(item: str, qty: int = 1) -> int:
    """Return the total price of the selected item in rupees."""
    return MENU[item.lower().strip()] * qty

